#!/bin/bash
# gen-fleet.sh: write a fleet file (engine/server/fleet.sh, engine/comm/fleet.cpp)
# from the tensor-parallel degree and the ssh targets, so the mechanical part —
# TP ranks, per-rank paths, link addresses — is not hand-typed.
#
#   WORKERS="u@spark1 u@spark2 u@spark3" fleet/gen-fleet.sh --out ~/fleet.conf   # 4 ranks
#   WORKERS="u@spark1"                   fleet/gen-fleet.sh --print              # 2 ranks
#
# The rank count is the list plus the head; TP in the environment (or DSGB10_TP)
# is only cross-checked against it, so two sources cannot disagree silently.
#
# What stays an input because it is a physical fact of the cabling: the RDMA
# device names (the same on every box) and GID_INDEX. The link addresses follow
# one scheme: link i joins ranks i and i+1 (mod TP), its PCI domain d subnet is
# 192.168.(LINK_BASE + 2i + d).0/24, rank i takes .1 and rank i+1 takes .2.
# Address the boxes to match, or override any value in the environment
# (RANK<r>_NEXT_IP<d>, RANK<r>_WEIGHTS, ...); an override always wins.
#
# Flags: --out FILE (default ./fleet.conf), --print (stdout, writes nothing),
#        --force (overwrite an existing FILE), --probe (read each box's
#        `hostname` over ssh and write RANK<r>_HOSTNAME).
set -u
REPO=$(cd "$(dirname "$0")/../.." && pwd)
FLEET_SH=$REPO/ds41f-4xgx10-switchless/engine/server/fleet.sh

TP=${TP:-${DSGB10_TP:-}}
GID_INDEX=${GID_INDEX:-3}
NEXT_DEV0=${NEXT_DEV0:-rocep1s0f0}
NEXT_DEV1=${NEXT_DEV1:-roceP2p1s0f0}
PREV_DEV0=${PREV_DEV0:-rocep1s0f1}
PREV_DEV1=${PREV_DEV1:-roceP2p1s0f1}
LINK_BASE=${LINK_BASE:-10}          # 2*TP subnets from 192.168.LINK_BASE.0
BIN_DIR=${BIN_DIR:-~/dsgb10/bin}
LOG_DIR=${LOG_DIR:-~/dsgb10/logs}
SERVICE_DIR=${SERVICE_DIR:-~/dsgb10/service}
RING_LOCK=${RING_LOCK:-/data/dsgb10/ring.lock}
# Not ${WEIGHTS:-...}: the `}` of `{rank}` would close the expansion.
# The directory dsw-prepare cuts into: rank 0 serves it in place, ./start.sh
# ships the other ranks' three files from it.
[ -n "${WEIGHTS:-}" ] || WEIGHTS='~/dsgb10/convert/rank{rank}.dsw'
HASHMAP=${HASHMAP:-'~/dsgb10/convert/engram/engram_hashmap.bin'}
ENGRAM=${ENGRAM:-'~/dsgb10/convert/engram'}
SPILL=${SPILL:-~/dsgb10/spill}

OUT=./fleet.conf PRINT=0 FORCE=0 PROBE=0
while [ $# -gt 0 ]; do
  case $1 in
    --out) OUT=${2:?--out needs a file}; shift 2 ;;
    --print) PRINT=1; shift ;;
    --force) FORCE=1; shift ;;
    --probe) PROBE=1; shift ;;
    -h | --help) awk 'NR > 1 && /^#/ { sub(/^# ?/, ""); print; next } NR > 1 { exit }' "$0"; exit 0 ;;
    *) echo "gen-fleet: unknown argument $1" >&2; exit 2 ;;
  esac
done

die() { echo "gen-fleet: $*" >&2; exit 1; }
# The rank count follows the targets when it is not given: the head is local and
# every ssh target in WORKERS is one more rank.
if [ -z "$TP" ]; then
  read -r -a _W <<< "${WORKERS:-${WORKER:-}}"
  [ "${#_W[@]}" -gt 0 ] ||
    die "set TP (2..16), or WORKERS=\"user@host ...\" and TP follows the target count"
  TP=$((${#_W[@]} + 1))
fi
[[ $TP =~ ^[0-9]+$ ]] && [ "$TP" -ge 2 ] && [ "$TP" -le 16 ] || die "TP='$TP': a ring is 2..16 ranks"
[[ $GID_INDEX =~ ^[0-9]+$ ]] || die "GID_INDEX='$GID_INDEX' is not a number"
[[ $LINK_BASE =~ ^[0-9]+$ ]] && [ $((LINK_BASE + 2 * TP - 1)) -le 255 ] || die "LINK_BASE='$LINK_BASE': 2*TP subnets must fit 192.168.0-255"

# Rank 0 is the head and runs locally; the fleet names only ranks 1..TP-1, so
# TP=2 takes one target (WORKER= is the same thing, as in MiaAI's recipe).
read -r -a W <<< "${WORKERS:-${WORKER:-}}"
[ "${#W[@]}" -eq $((TP - 1)) ] ||
  die "TP=$TP needs $((TP - 1)) ssh target(s) and WORKERS lists ${#W[@]}: the rank count follows WORKERS now, so drop TP, or list the other $((TP - 1)) target(s) (rank 0 is the head, local)"

# A value from the environment if set, else the generated one.
pick() { local v="RANK$1_$2"; printf '%s' "${!v:-$3}"; }
# The per-rank paths carry a {rank} slot, so one pattern fits every rank.
ranked() { local v; v=$(pick "$1" "$2" "$3"); printf '%s' "${v//\{rank\}/$1}"; }

L=()
add() { L+=("$1=$2"); }

L+=("# Generated by fleet/gen-fleet.sh: TP=$TP, links 192.168.$LINK_BASE.0/24 .. 192.168.$((LINK_BASE + 2 * TP - 1)).0/24.")
L+=("# Edit the environment and re-run rather than hand-editing; unknown or duplicate keys are refused.")
add GID_INDEX "$GID_INDEX"
add NEXT_DEV0 "$NEXT_DEV0"
add NEXT_DEV1 "$NEXT_DEV1"
add PREV_DEV0 "$PREV_DEV0"
add PREV_DEV1 "$PREV_DEV1"
add BIN_DIR "$BIN_DIR"
add LOG_DIR "$LOG_DIR"
add SERVICE_DIR "$SERVICE_DIR"
add RING_LOCK "$RING_LOCK"

for ((r = 0; r < TP; r++)); do
  next_link=$r
  prev_link=$(((r + TP - 1) % TP))
  add "RANK${r}_NAME" "$(pick "$r" NAME "rank$r")"
  if [ "$PROBE" = 1 ]; then
    if [ "$r" = 0 ]; then h=$(hostname 2> /dev/null) || h=""
    else h=$(ssh -o BatchMode=yes -o ConnectTimeout=5 "${W[r - 1]}" hostname 2> /dev/null) || h=""
    fi
    [ -n "$h" ] && add "RANK${r}_HOSTNAME" "$(pick "$r" HOSTNAME "$h")"
  elif [ -n "$(pick "$r" HOSTNAME "")" ]; then
    add "RANK${r}_HOSTNAME" "$(pick "$r" HOSTNAME "")"
  fi
  [ "$r" = 0 ] || add "RANK${r}_SSH" "${W[r - 1]}"
  for d in 0 1; do
    add "RANK${r}_NEXT_IP${d}" "$(pick "$r" "NEXT_IP${d}" "192.168.$((LINK_BASE + 2 * next_link + d)).1")"
    add "RANK${r}_PREV_IP${d}" "$(pick "$r" "PREV_IP${d}" "192.168.$((LINK_BASE + 2 * prev_link + d)).2")"
  done
  add "RANK${r}_WEIGHTS" "$(ranked "$r" WEIGHTS "$WEIGHTS")"
  add "RANK${r}_HASHMAP" "$(ranked "$r" HASHMAP "$HASHMAP")"
  add "RANK${r}_ENGRAM" "$(ranked "$r" ENGRAM "$ENGRAM")"
  add "RANK${r}_ENGRAM_READ_BATCH" "$(pick "$r" ENGRAM_READ_BATCH 1)"
  add "RANK${r}_SPILL" "$(pick "$r" SPILL "$SPILL")"
done

if [ "$PRINT" = 1 ]; then
  printf '%s\n' "${L[@]}"
  exit 0
fi
[ -e "$OUT" ] && [ "$FORCE" != 1 ] && die "$OUT exists (--force to overwrite)"
mkdir -p "$(dirname "$OUT")"
tmp=$OUT.tmp.$$
printf '%s\n' "${L[@]}" > "$tmp" || die "cannot write $tmp"
# The scripts' own reader is the validator: unknown keys, duplicates and
# unreadable values fail here, not at the engine's start.
if ! (export TP; . "$FLEET_SH"; fleet_load "$tmp") 2>&1; then
  rm -f "$tmp"
  die "the generated file does not pass fleet_load (above); nothing written"
fi
mv -f "$tmp" "$OUT"
echo "gen-fleet: wrote $OUT (TP=$TP, ranks 0..$((TP - 1)), $((TP - 1)) worker(s))"
echo "gen-fleet: next: FLEET=$OUT ./start.sh   (address the boxes on the links as the file says, or override RANK<r>_*_IP<d>)"
